#!/usr/bin/env bash
# Copies the Lua scripts from internal/limiter/scripts into every SDK, so the
# service and the SDKs always run the same code. Run after editing a script.
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
src="$root/internal/limiter/scripts"

# Verbatim copies.
for dir in sdk/ruby/lib/fairshare/scripts sdk/php/src/scripts sdk/java/src/main/resources/fairshare sdk/rust/scripts; do
  mkdir -p "$root/$dir"
  cp "$src"/acquire.lua "$src"/cooldown.lua "$src"/sync.lua "$root/$dir/"
done

# Embedded as string constants.
python3 - "$src" "$root" <<'PY'
import pathlib, sys
src, root = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
names = ["acquire", "cooldown", "sync"]
luas = {n: (src / f"{n}.lua").read_text() for n in names}
for lua in luas.values():
    assert "`" not in lua and "${" not in lua and "\\" not in lua and '"""' not in lua, "script contains a character the embedders cannot quote"
header = "GENERATED by sdk/scripts/sync-scripts.sh from internal/limiter/scripts. Do not edit."
ts = [f"// {header}", ""] + [f"export const {n.upper()} = `{luas[n]}`;\n" for n in names]
(root / "sdk/typescript/src/scripts.ts").write_text("\n".join(ts))
py = [f"# {header}", ""] + [f'{n.upper()} = """{luas[n]}"""\n' for n in names]
(root / "sdk/python/fairshare/_scripts.py").write_text("\n".join(py))
PY
echo "synced Lua scripts into sdk/{ruby,php,java,rust,typescript,python}"
